// Copies the website's Hindi dictionaries into the app. Reads frontend/ only; writes mobile/ only.
// Run after the website's Hindi lists change: npm run i18n
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const from = join(root, '..', 'frontend', 'src', 'lib', 'i18n');
const to = join(root, 'src', 'i18n', 'generated');

const files = readdirSync(from).filter((f) => /^hi(-[\w-]+)?\.js$/.test(f)).sort();
if (!files.includes('hi.js')) throw new Error(`hi.js not found in ${from}`);

rmSync(to, { recursive: true, force: true });
mkdirSync(to, { recursive: true });
for (const f of files) {
  writeFileSync(join(to, f), `// GENERATED from frontend/src/lib/i18n/${f} by scripts/sync-hindi.mjs. Do not edit.\n${readFileSync(join(from, f), 'utf8')}`);
}
writeFileSync(
  join(to, 'hi.d.ts'),
  '// GENERATED by scripts/sync-hindi.mjs. Do not edit.\nexport const EXACT: Record<string, string>;\nexport const PATTERNS: [RegExp, string | ((...found: string[]) => string | undefined)][];\n',
);
console.log(`Copied ${files.length} Hindi files.`);
