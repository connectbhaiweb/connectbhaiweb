/* Copies the website's own animated artwork (hero story, Care plan card, How-it-works pictures, Care page art) into the app,
   so it looks and moves exactly like the website. Re-run after the website's artwork changes:  node scripts/build-web-art.mjs */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'frontend', 'src');
const read = (p) => readFileSync(join(root, p), 'utf8');
const globals = read('app/globals.css'), dash = read('app/dashboard.css');
const ui = read('lib/connectbhai/ui.js'), storyJs = read('lib/connectbhai/storyTemplate.js');

/* ---- CSS: keep the rules for the artwork, all @keyframes, and the matching rules inside @media ---- */
const WANT = /(^|[\s,>+~.])(story|stage|sc\d*|carecard|cc-[\w-]+|step-art|step-top|step-ico|step|steps3|care-art|care-hero|care-visual|care-copy|care-steps|cstep[\w-]*|hero-side|meet)\b/;
function blocks(css) {
  const out = []; let i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i); if (open < 0) break;
    let depth = 1, j = open + 1;
    while (j < css.length && depth) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
    out.push([css.slice(i, open).trim().replace(/\/\*[\s\S]*?\*\//g, '').trim(), css.slice(open + 1, j - 1)]); i = j;
  }
  return out;
}
function pick(css) {
  let out = '';
  for (const [sel, body] of blocks(css)) {
    if (sel.startsWith('@keyframes')) out += `${sel}{${body}}\n`;
    else if (sel.startsWith('@media')) { const inner = pick(body); if (inner.trim() && !/prefers-color-scheme/.test(sel)) out += `${sel}{${inner}}\n`; }
    else if (sel.startsWith('@')) continue;
    else if (WANT.test(sel)) out += `${sel}{${body}}\n`;
  }
  return out;
}
const root0 = globals.match(/:root\{([\s\S]*?)\n\}/)[1];
const css = `@import url('https://fonts.googleapis.com/css2?family=Manrope:wght@500;600;700;800&family=Sora:wght@600;700;800&display=swap');
:root{${root0}}
*{box-sizing:border-box}html,body{margin:0;padding:0;background:transparent;font-family:var(--body);color:var(--ink);-webkit-text-size-adjust:100%}
h3,b{font-family:var(--display)}
${pick(globals)}
${pick(dash)}`;

/* ---- Markup, taken verbatim from the website ---- */
const story = storyJs.match(/const STORY_HTML = `([\s\S]*?)`;/)[1];
const careIdx = ui.indexOf('<div class="carecard">');
const careEnd = ui.indexOf('<p class="meet">', careIdx);
const carecard = ui.slice(careIdx, careEnd).replace(/\s*<\/div>\s*$/, '').trim();
const s3 = ui.indexOf('<div class="steps3">'), s3end = ui.indexOf('</div>\n  </div></section>', s3);
const stepsHtml = ui.slice(s3 + '<div class="steps3">'.length, s3end);
const steps = stepsHtml.split('<div class="step">').slice(1).map((x) => `<div class="step">${x}`.replace(/\s*$/, ''));
const careArt = ui.match(/<svg class="care-art"[\s\S]*?<\/svg>/)[0];

const esc = (s) => JSON.stringify(s);
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'web-art.generated.ts'),
`/* GENERATED by scripts/build-web-art.mjs from the website's own files. Do not edit by hand. */
export const ART_CSS = ${esc(css)};
export const ART_STORY = ${esc(story)};
export const ART_CARECARD = ${esc(carecard)};
export const ART_STEPS: string[] = ${esc(steps)};
export const ART_CARE = ${esc(careArt)};
`);
console.log({ cssBytes: css.length, story: story.length, carecard: carecard.length, steps: steps.length, careArt: careArt.length });
